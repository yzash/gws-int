def test_outputs_written(tmp_path, summary, events, cache):
    scoped = transform.scoped_events(events, summary, USAGE)
    org = transform.build_org_summary(summary, scoped, start_time=cache["start_time"],
                                      end_time=cache["end_time"], window_days=28)
    paths = report.write_csvs(tmp_path, "2026-09-25", events, summary, org)
    raw = pd.read_csv(paths["raw_events"])
    assert list(raw.columns) == transform.RAW_COLUMNS
    us = pd.read_csv(paths["user_summary"])
    assert list(us.columns) == transform.USER_COLUMNS
    dash = report.render_dashboard(tmp_path, "2026-09-25",
                                   report.dashboard_context(summary, scoped, org))
    html = dash.read_text()
    assert "user1@example.com" in html and "user6@example.com" in html
    assert "203.0.113." not in html            # IPs never reach the dashboard
    assert "<script" not in html and "http://" not in html  # self-contained, no external calls
    assert (tmp_path / "dashboard_2026-09-25.html").exists()


def test_scope_guard():
    assert validate_scopes(list(ALLOWED_SCOPES)) == list(ALLOWED_SCOPES)
    with pytest.raises(ConfigError):
        validate_scopes(list(ALLOWED_SCOPES) + ["https://www.googleapis.com/auth/admin.directory.user"])
    with pytest.raises(ConfigError):
        validate_scopes(ALLOWED_SCOPES[:1])
