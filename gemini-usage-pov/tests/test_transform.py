from pathlib import Path

import pandas as pd
import pytest

from src import report, transform
from src.config import ALLOWED_SCOPES, ConfigError, validate_scopes

FIXTURE = Path(__file__).parent / "fixtures" / "sample_cache.json"
USAGE = ["feature_utilization"]


@pytest.fixture(autouse=True)
def no_network(monkeypatch):
    def guard(*a, **k):
        raise RuntimeError("tests must not touch the network")
    monkeypatch.setattr(socket, "create_connection", guard)
    monkeypatch.setattr(socket.socket, "connect", guard)


@pytest.fixture(scope="module")
def cache():
    return json.loads(FIXTURE.read_text())


@pytest.fixture(scope="module")
def events(cache):
    return transform.flatten(cache["activities"])


