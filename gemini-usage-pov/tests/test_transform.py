def test_totals_and_tiers(summary):
    s = summary.set_index("user_email")
    assert s.loc["user1@example.com", "total_actions"] == 31   # 30 + second event in one activity
    assert s.loc["user2@example.com", "total_actions"] == 13
    assert s.loc["user4@example.com", "total_actions"] == 5
    assert s.loc["user1@example.com", "tier"] == "High"
    assert s.loc["user2@example.com", "tier"] == "Medium"
    assert s.loc["user4@example.com", "tier"] == "Medium"
    assert s.loc["user5@example.com", "tier"] == "Low"
    assert s.loc["user4@example.com", "other"] == 1
    # Per-app columns add up to the total.
    assert (summary[transform.APP_COLUMNS].sum(axis=1) == summary["total_actions"]).all()
    assert summary["total_actions"].sum() == 58
    assert summary["user_email"].iloc[0] == "user1@example.com"   # sorted by actions


