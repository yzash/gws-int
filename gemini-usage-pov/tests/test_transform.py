def test_suspended_users(events, cache, summary):
    assert "user9@example.com" not in set(summary["user_email"])
    incl = transform.build_user_summary(events, cache["users"], usage_event_names=USAGE,
                                        include_suspended=True)
    s = incl.set_index("user_email")
    assert s.loc["user9@example.com", "total_actions"] == 3
    assert bool(s.loc["user10@example.com", "suspended"]) is True
    assert len(incl) == len(summary) + 2


def test_ou_filter(events, cache):
    s = transform.build_user_summary(events, cache["users"], usage_event_names=USAGE,
                                     ou_filter=["/Sales"])
    # Sub-OUs are included; suspended and not-in-directory users are not.
    assert set(s["user_email"]) == {"user1@example.com", "user2@example.com",
                                    "user3@example.com", "user7@example.com"}
    s = transform.build_user_summary(events, cache["users"], usage_event_names=USAGE,
                                     ou_filter=["/Sales/APAC"])
    assert set(s["user_email"]) == {"user3@example.com", "user7@example.com"}
    # "/Sal" must not match "/Sales".
    s = transform.build_user_summary(events, cache["users"], usage_event_names=USAGE,
                                     ou_filter=["/Sal"])
    assert s.empty


def test_active_days_and_timezone(events, cache):
    utc = transform.build_user_summary(events, cache["users"], usage_event_names=USAGE)
    sgt = transform.build_user_summary(events, cache["users"], usage_event_names=USAGE,
                                       tz="Asia/Singapore")
    u = utc.set_index("user_email")
    assert 1 <= u.loc["user1@example.com", "active_days"] <= 28
    assert u.loc["user5@example.com", "active_days"] == 1
    assert (sgt["total_actions"].values == utc["total_actions"].values).all()
    assert (u["last_used"].dropna() >= u["first_used"].dropna()).all()


def test_org_summary(summary, events, cache):
    scoped = transform.scoped_events(events, summary, USAGE)
    org = transform.build_org_summary(summary, scoped, start_time=cache["start_time"],
                                      end_time=cache["end_time"], window_days=28)
    m = dict(zip(org["metric"], org["value"]))
    assert m["total_users"] == 9
    assert m["active_users"] == 6
    assert m["adoption_pct"] == round(100 * 6 / 9, 1)
    assert m["total_actions"] == 58
    assert sum(m[f"actions_{a}"] for a in transform.APP_COLUMNS) == 58
    assert m["users_tier_zero"] == 3 and m["users_tier_high"] == 1
    assert "top_feature_1" in m and "top_feature_11" not in m
    assert m["adoption_pct_ou:/Engineering"] == "66.7 (2/3)"
    assert scoped["user_email"].isin(summary["user_email"]).all()


def test_compare(summary, events, cache):
    scoped = transform.scoped_events(events, summary, USAGE)
    org = transform.build_org_summary(summary, scoped, start_time=cache["start_time"],
                                      end_time=cache["end_time"], window_days=28)
    prev = org.copy()
    prev.loc[prev["metric"] == "active_users", "value"] = 4
    diff = transform.compare_org_summaries(prev, org).set_index("metric")
    assert diff.loc["active_users", "change"] == 2
    assert diff.loc["total_actions", "change"] == 0


